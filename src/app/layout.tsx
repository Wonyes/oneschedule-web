import type { Metadata } from "next";
import { Geist, Plus_Jakarta_Sans } from "next/font/google";
import { cookies } from "next/headers";
import "./globals.css";
import Providers from "./providers";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const jakarta = Plus_Jakarta_Sans({
  subsets: ["latin"],
  variable: "--font-main",
  weight: ["400", "500", "600", "700"],
});

export const metadata: Metadata = {
  title: "Schedule",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const cookieStore = await cookies();
  // 쿠키 기반으로 서버에서부터 테마를 확정해 렌더링한다.
  // localStorage/인라인 스크립트 방식은 router.refresh() 등으로 <html>이
  // 다시 렌더링될 때마다 서버가 모르는 속성이라 사라져버려서 쓸 수 없다.
  const theme = cookieStore.get("theme")?.value === "light" ? "light" : undefined;

  return (
    <html
      lang="ko"
      data-theme={theme}
      className={`${geistSans.variable} ${geistMono.variable} ${jakarta.variable} antialiased`}
    >
      <body className="bg-main-bg w-full h-screen flex justify-center">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
